// NormalizeRegion 把任意 region 值归一为 34 个省级行政单位（直辖市/自治区/省/特别行政区）的简称口径：
// 地级市映射回所属省（广州市→广东），自治区全/简称统一为简称（广西壮族自治区→广西），
// 港澳台视同省级行政区。无法归一的值返回空串（由聚合方计入「其他」）。
func NormalizeRegion(r string) string {
	r = strings.TrimSpace(r)
	if r == "" {
		return ""
	}
	switch r {
	// 已是简称的 34 个省级行政单位，原样返回
	case "北京", "上海", "天津", "重庆",
		"河北", "山西", "辽宁", "吉林", "黑龙江", "江苏", "浙江", "安徽",
		"福建", "江西", "山东", "河南", "湖北", "湖南", "广东", "海南",
		"四川", "贵州", "云南", "陕西", "甘肃", "青海",
		"内蒙古", "广西", "西藏", "宁夏", "新疆", "香港", "澳门", "台湾":
		return r
	case "北京市":
		return "北京"
	case "上海市":
		return "上海"
	case "天津市":
		return "天津"
	case "重庆市":
		return "重庆"
	case "香港特别行政区":
		return "香港"
	case "澳门特别行政区":
		return "澳门"
	case "台湾省":
		return "台湾"
	case "内蒙古自治区":
		return "内蒙古"
	case "广西壮族自治区":
		return "广西"
	case "西藏自治区":
		return "西藏"
	case "宁夏回族自治区":
		return "宁夏"
	case "新疆维吾尔自治区":
		return "新疆"
	}
	if strings.HasSuffix(r, "省") {
		return strings.TrimSuffix(r, "省")
	}
	bare := strings.TrimSuffix(r, "市")
	if p, ok := cityProvince[bare]; ok {
		return p
	}
	return ""
}

